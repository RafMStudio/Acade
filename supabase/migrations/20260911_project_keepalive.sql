create extension if not exists pg_cron;

create table if not exists public.project_keepalive (
  id bigint generated by default as identity primary key,
  pinged_at timestamptz not null default now(),
  source text not null default 'supabase_cron'
);

alter table public.project_keepalive enable row level security;

revoke all on table public.project_keepalive from anon;
revoke insert, update, delete on table public.project_keepalive from authenticated;
grant select on table public.project_keepalive to authenticated;

create policy "System administrators can view keepalive status"
on public.project_keepalive
for select
to authenticated
using (public.is_system_admin());

insert into public.project_keepalive (source)
select 'setup'
where not exists (select 1 from public.project_keepalive);

select cron.schedule(
  'acadeloop-project-keepalive',
  '17 6 * * *',
  $$
    insert into public.project_keepalive (source)
    select 'supabase_cron'
    where not exists (
      select 1
      from public.project_keepalive
      where pinged_at > now() - interval '5 days'
    );
  $$
);